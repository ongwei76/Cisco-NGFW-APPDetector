"""Maintainer-curated Lua detector library.

Users never need a GitHub account:

1. A user builds a *submission package* (ZIP with the Lua and ``submission.json``)
   and emails it to the maintainer.
2. The maintainer reviews it offline with a separate, private tool and publishes
   it to a public GitHub repository. The submitter's email is never published.
3. Every installation resolves the latest branch commit through GitHub's
   anonymous Git protocol and reads the index and Lua at that immutable commit.
   Branch-cache fallbacks are clearly labeled. Each Lua is verified against
   the SHA256 recorded in the index.

Repository layout::

    library/index.json
    library/<AppName>/<version>/<AppName>.lua
    library/<AppName>/<version>/metadata.json

This program only reads the library; it contains no GitHub write access.
"""

from __future__ import annotations

import hashlib
import io
import json
import logging
import os
import re
import time
import urllib.request
import zipfile
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Optional

import requests

SUBMISSION_KIND = "ngfw-lua-submission"
MANIFEST_NAME = "submission.json"
MAX_LUA_BYTES = 256 * 1024
INDEX_CACHE_SEC = 60
LOG = logging.getLogger(__name__)

APP_NAME_RE = re.compile(r"^[A-Za-z_]{1,15}$")
EMAIL_RE = re.compile(r"^[^@\s<>\"'`]{1,64}@[A-Za-z0-9.-]{1,253}\.[A-Za-z]{2,63}$")
GITHUB_NAME_RE = re.compile(r"^[A-Za-z0-9_.-]{1,100}$")
BRANCH_RE = re.compile(r"^[A-Za-z0-9_./-]{1,200}$")
DIR_RE = re.compile(r"^[A-Za-z0-9_-]{1,64}$")
# gHostPatternList is the current generator format; the others are from
# detectors generated by earlier versions of this tool.
HOST_LIST_NAMES = ("gHostPatternList", "gTlsExactHosts", "gTlsCertCNs", "gTlsHostSuffixes", "gHttpHosts")
HOST_LIST_RE = re.compile(r"\b(?:" + "|".join(HOST_LIST_NAMES) + r")\s*=\s*\{(?P<body>.*?)\}", re.S)
LUA_TOKEN_RE = re.compile(r'"((?:[^"\\]|\\.)*)"|--[^\n]*')

# Built-in FMC application categories (FMC 10.0 "Add Category" list). The import
# resolves names against the target FMC, so only the name is stored.
FMC_CATEGORIES = (
    "active directory", "ad portal", "anonymizer/proxy", "application development and testing",
    "backup and recovery", "browser plugin", "business", "cip admin", "cip ra admin", "cip ra read",
    "cip ra write", "cip read", "cip write", "cloud carrier", "collaboration", "compute",
    "content delivery network", "content management", "customer relationship management (CRM)",
    "database", "download manager", "e-commerce", "education", "email", "enterprise resource planning",
    "financial", "gaming", "generative ai", "government services", "healthcare services",
    "human resources", "instant messaging", "legal", "marketing and sales", "messaging queues",
    "mobile application", "multimedia (music/audio)", "multimedia (other)", "multimedia (tv/video)",
    "network protocols/services", "network utilities", "news", "others", "pacs", "peer to peer",
    "remote administration", "remote desktop control", "remote file storage", "search engine",
    "security management", "service management", "shopping", "sms tools", "social networking",
    "software repository", "software update", "travel", "virtual worlds", "voip", "vpn/tunnel",
    "web browser", "web conferencing", "web content aggregators", "web desktop",
    "web services provider", "web spider/search crawler", "website",
)
DEFAULT_CATEGORY = "others"
# FMC risk / business relevance scale: 1 Very Low … 5 Very High.
LEVEL_RANGE = range(1, 6)
DEFAULT_RISK = 2
DEFAULT_RELEVANCE = 3


class SharingError(Exception):
    """Raised for user-actionable sharing failures."""


class LibraryNotFound(SharingError):
    """The authoritative index is missing, or all fallback sources answered 404."""


def normalize_nickname(value: str) -> str:
    text = " ".join(str(value or "").split())
    if not 1 <= len(text) <= 32:
        raise SharingError("nickname must be 1-32 characters")
    if any(ch in text for ch in "<>\"'`"):
        raise SharingError("nickname contains unsupported characters")
    return text


def normalize_email(value: str) -> str:
    text = str(value or "").strip()
    if not EMAIL_RE.match(text):
        raise SharingError("email address is invalid")
    return text


def normalize_category(value: Any) -> str:
    text = " ".join(str(value or "").split())
    for name in FMC_CATEGORIES:
        if name.casefold() == text.casefold():
            return name
    raise SharingError("category must be one of the FMC application categories")


def normalize_level(value: Any, label: str) -> int:
    try:
        level = int(value)
    except (TypeError, ValueError) as e:
        raise SharingError(f"{label} must be 1-5") from e
    if level not in LEVEL_RANGE:
        raise SharingError(f"{label} must be 1-5")
    return level


def _index_category(value: Any) -> str:
    try:
        return normalize_category(value)
    except SharingError:
        return ""


def _index_level(value: Any) -> int:
    """0 means "not set" for entries published before these fields existed."""
    return value if isinstance(value, int) and not isinstance(value, bool) and value in LEVEL_RANGE else 0


def sha256_hex(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def parse_branch_head(data: bytes, branch: str) -> str:
    target = b"refs/heads/" + branch.encode("utf-8")
    offset = 0
    while offset < len(data):
        prefix = data[offset:offset + 4]
        try:
            length = int(prefix, 16)
        except ValueError as e:
            raise SharingError("GitHub returned an invalid Git ref advertisement") from e
        if len(prefix) != 4 or (length != 0 and length < 4) or offset + length > len(data):
            raise SharingError("GitHub returned a truncated Git ref advertisement")
        if length == 0:
            offset += 4
            continue
        packet = data[offset + 4:offset + length]
        offset += length
        fields = packet.split(b"\0", 1)[0].rstrip(b"\n").split(b" ", 1)
        if len(fields) == 2 and fields[1] == target:
            if not re.fullmatch(rb"[0-9a-f]{40}", fields[0]):
                raise SharingError("GitHub returned an invalid branch commit")
            return fields[0].decode("ascii")
    raise SharingError("the configured branch was not advertised by GitHub")


def _text(value: Any, limit: int) -> str:
    return str(value if value is not None else "")[:limit]


def extract_host_patterns(lua_text: str) -> list[str]:
    patterns: list[str] = []
    for match in HOST_LIST_RE.finditer(lua_text):
        for token in LUA_TOKEN_RE.finditer(match.group("body")):
            value = token.group(1)
            if value and value not in patterns:
                patterns.append(value)
    return patterns


def build_submission(
    *,
    app_name: str,
    lua_bytes: bytes,
    nickname: str,
    email: str,
    fmc_version: str,
    notes: str,
    tool_version: str,
    category: str,
    risk: int = DEFAULT_RISK,
    business_relevance: int = DEFAULT_RELEVANCE,
) -> tuple[str, bytes, dict[str, Any]]:
    if not APP_NAME_RE.match(app_name):
        raise SharingError("invalid application name")
    if len(lua_bytes) > MAX_LUA_BYTES:
        raise SharingError("Lua file is too large")
    created = datetime.now(timezone.utc)
    manifest = {
        "schema": 1,
        "kind": SUBMISSION_KIND,
        "app_name": app_name,
        "lua_file": f"{app_name}.lua",
        "sha256": sha256_hex(lua_bytes),
        "size": len(lua_bytes),
        "submitter": {"nickname": normalize_nickname(nickname), "email": normalize_email(email)},
        "fmc_version": _text(fmc_version, 64).strip(),
        "category": normalize_category(category),
        "risk": normalize_level(risk, "risk"),
        "business_relevance": normalize_level(business_relevance, "business relevance"),
        "notes": _text(notes, 2000).strip(),
        "tool_version": tool_version,
        "created_at": created.isoformat(timespec="seconds"),
        "host_patterns": extract_host_patterns(lua_bytes.decode("utf-8", errors="replace")),
    }
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr(MANIFEST_NAME, json.dumps(manifest, ensure_ascii=False, indent=2))
        zf.writestr(manifest["lua_file"], lua_bytes)
    filename = f"NGFW-Lua-Submission-{app_name}-{created.strftime('%Y%m%d-%H%M%S')}.zip"
    return filename, buffer.getvalue(), manifest


# ── library location / index ───────────────────────────────────────────────


@dataclass(frozen=True)
class LibraryLocation:
    owner: str
    repo: str
    branch: str = "main"
    directory: str = "library"
    mirror_fallback: bool = True

    def __post_init__(self) -> None:
        if not GITHUB_NAME_RE.match(self.owner) or not GITHUB_NAME_RE.match(self.repo):
            raise SharingError("library GitHub owner/repository is invalid")
        if not BRANCH_RE.match(self.branch) or not DIR_RE.match(self.directory):
            raise SharingError("library branch or directory is invalid")

    @property
    def index_path(self) -> str:
        return f"{self.directory}/index.json"

    @property
    def lua_path_re(self) -> re.Pattern[str]:
        return re.compile(
            rf"^{re.escape(self.directory)}/(?P<app>[A-Za-z_]{{1,15}})/(?P<version>[1-9][0-9]{{0,3}})/(?P=app)\.lua$"
        )

    def lua_path(self, app_name: str, version: int) -> str:
        return f"{self.directory}/{app_name}/{version}/{app_name}.lua"

    def urls(self, path: str, ref: Optional[str] = None) -> list[tuple[str, str]]:
        revision = ref or self.branch
        sources = [("github", f"https://raw.githubusercontent.com/{self.owner}/{self.repo}/{revision}/{path}")]
        if self.mirror_fallback:
            sources.append(("jsdelivr", f"https://cdn.jsdelivr.net/gh/{self.owner}/{self.repo}@{revision}/{path}"))
        return sources

    @property
    def repo_url(self) -> str:
        return f"https://github.com/{self.owner}/{self.repo}/tree/{self.branch}/{self.directory}"


def sanitize_index_entry(raw: Any, location: LibraryLocation) -> Optional[dict[str, Any]]:
    if not isinstance(raw, dict):
        return None
    lua_path = str(raw.get("lua_path", ""))
    match = location.lua_path_re.match(lua_path)
    sha = _text(raw.get("sha256"), 64).lower()
    if not match or not re.fullmatch(r"[0-9a-f]{64}", sha):
        return None
    return {
        "app_name": match.group("app"),
        "version": int(match.group("version")),
        "lua_path": lua_path,
        "sha256": sha,
        "size": int(raw.get("size") or 0) if str(raw.get("size", "")).isdigit() else 0,
        "nickname": _text(raw.get("nickname"), 32) or "-",
        "fmc_version": _text(raw.get("fmc_version"), 64),
        "tool_version": _text(raw.get("tool_version"), 32),
        "category": _index_category(raw.get("category")),
        "risk": _index_level(raw.get("risk")),
        "business_relevance": _index_level(raw.get("business_relevance")),
        "notes": _text(raw.get("notes"), 2000),
        "review_note": _text(raw.get("review_note"), 2000),
        "submitted_at": _text(raw.get("submitted_at"), 40),
        "published_at": _text(raw.get("published_at"), 40),
        "host_patterns": [_text(p, 255) for p in raw.get("host_patterns", [])][:200]
        if isinstance(raw.get("host_patterns"), list)
        else [],
    }


def parse_index(data: bytes, location: LibraryLocation) -> list[dict[str, Any]]:
    try:
        payload = json.loads(data.decode("utf-8"))
    except (ValueError, UnicodeDecodeError) as e:
        raise SharingError("library index.json is not valid JSON") from e
    raw_entries = payload.get("entries") if isinstance(payload, dict) else None
    if not isinstance(raw_entries, list):
        raise SharingError("library index.json has no entries list")
    entries = [e for e in (sanitize_index_entry(r, location) for r in raw_entries) if e]
    return sorted(entries, key=lambda e: (e["app_name"].casefold(), -e["version"]))


def system_proxies() -> dict[str, str]:
    """Windows system proxy for GitHub/jsDelivr access.

    Python ignores the registry proxy as soon as any ``*_proxy`` variable
    (even only ``NO_PROXY``) is set, which breaks networks that require the
    system proxy. Explicit ``HTTP(S)_PROXY`` variables still take precedence.
    """
    env = urllib.request.getproxies_environment()
    if env.get("http") or env.get("https") or os.name != "nt":
        return {}
    try:
        registry = urllib.request.getproxies_registry()
    except OSError:
        return {}
    return {k: v for k, v in registry.items() if k in ("http", "https")}


def new_http_session() -> requests.Session:
    session = requests.Session()
    session.proxies.update(system_proxies())
    return session


@dataclass
class LibraryClient:
    """Anonymous, read-only access to the published library."""

    location: LibraryLocation
    session: Optional[requests.Session] = None
    timeout: float = 10.0
    _cache: Optional[tuple[float, list[dict[str, Any]], str, Optional[str]]] = field(default=None, init=False)

    def __post_init__(self) -> None:
        self.session = self.session or new_http_session()

    def _branch_head(self) -> str:
        loc = self.location
        url = f"https://github.com/{loc.owner}/{loc.repo}.git/info/refs"
        try:
            response = self.session.get(
                url, params={"service": "git-upload-pack"},
                headers={"Cache-Control": "no-cache"}, timeout=self.timeout,
            )
        except requests.RequestException as e:
            raise SharingError(f"github-head: {e.__class__.__name__}") from e
        if response.status_code != 200:
            raise SharingError(f"github-head: HTTP {response.status_code}")
        return parse_branch_head(response.content, loc.branch)

    def _fetch(self, path: str, bust: bool = False, ref: Optional[str] = None) -> tuple[bytes, str]:
        errors = []
        for source, url in self.location.urls(path, ref):
            params = {}
            headers = {}
            if bust:
                params["t"] = str(time.time_ns())
                headers["Cache-Control"] = "no-cache"
            try:
                response = self.session.get(url, params=params or None, headers=headers, timeout=self.timeout)
            except requests.RequestException as e:
                errors.append(f"{source}: {e.__class__.__name__}")
                continue
            if response.status_code == 200:
                return response.content, source + "-commit" if ref else source
            errors.append(f"{source}: HTTP {response.status_code}")
        message = "library is not reachable (" + "; ".join(errors) + ")"
        if all(e.endswith("HTTP 404") for e in errors):
            raise LibraryNotFound(message)
        raise SharingError(message)

    def _snapshot(self, force: bool = False) -> tuple[list[dict[str, Any]], str, Optional[str]]:
        if not force and self._cache and time.monotonic() - self._cache[0] < INDEX_CACHE_SEC:
            return self._cache[1], self._cache[2], self._cache[3]
        ref = None
        try:
            try:
                ref = self._branch_head()
                data, source = self._fetch(self.location.index_path, bust=force, ref=ref)
            except LibraryNotFound:
                raise
            except SharingError as live_error:
                LOG.warning("Live library index unavailable (%s); using branch caches with possible delayed changes", live_error)
                ref = None
                try:
                    data, source = self._fetch(self.location.index_path, bust=force)
                except SharingError as cache_error:
                    raise SharingError(f"{live_error}; {cache_error}") from cache_error
            entries = parse_index(data, self.location)
        except LibraryNotFound:
            entries, source = [], "empty"
            ref = None
        self._cache = (time.monotonic(), entries, source, ref)
        return entries, source, ref

    def entries(self, force: bool = False) -> tuple[list[dict[str, Any]], str]:
        entries, source, _ = self._snapshot(force)
        return entries, source

    def invalidate(self) -> None:
        self._cache = None

    def find(self, app_name: str, version: int) -> tuple[dict[str, Any], Optional[str]]:
        for force in (False, True):
            entries, _, ref = self._snapshot(force)
            for entry in entries:
                if entry["app_name"] == app_name and entry["version"] == version:
                    return entry, ref
        raise SharingError("detector is not in the library index")

    def read_lua(self, app_name: str, version: int) -> tuple[bytes, dict[str, Any], bool]:
        entry, ref = self.find(app_name, version)
        data, _ = self._fetch(entry["lua_path"], ref=ref)
        return data, entry, sha256_hex(data) == entry["sha256"]


# ── local settings ─────────────────────────────────────────────────────────


class SharingStore:
    """Remembers the submitter's nickname/email and reads the shared library."""

    def __init__(
        self,
        settings_path: Path,
        location: LibraryLocation,
        http_session: Optional[requests.Session] = None,
    ) -> None:
        self.settings_path = settings_path
        self.location = location
        self.client = LibraryClient(location, session=http_session)

    def load(self) -> dict[str, str]:
        settings = {"nickname": "", "email": ""}
        if self.settings_path.exists():
            try:
                data = json.loads(self.settings_path.read_text(encoding="utf-8"))
            except (OSError, ValueError):
                data = {}
            if isinstance(data, dict):
                settings.update({k: str(data[k]) for k in settings if k in data})
        return settings

    def remember_submitter(self, nickname: str, email: str) -> None:
        payload = {"nickname": nickname, "email": email}
        self.settings_path.parent.mkdir(parents=True, exist_ok=True)
        temporary = self.settings_path.with_suffix(".json.tmp")
        temporary.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
        temporary.replace(self.settings_path)
